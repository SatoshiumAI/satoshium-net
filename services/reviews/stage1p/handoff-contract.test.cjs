'use strict';
const assert=require('node:assert/strict');
const {inspectHandoff,FIELDS,INSTITUTIONS}=require('./handoff-contract.cjs');
const fixture=require('./fictional-handoff.json');
let count=0;
function check(name,mutation,classification,code){
 const input=structuredClone(fixture);
 const changed=mutation(input);
 const output=inspectHandoff(changed===undefined?input:changed);
 assert.equal(output.classification,classification,name);
 assert.equal(output.authority_granted,false,name);
 assert.equal(output.institutional_outcome,'NOT_DETERMINED',name);
 assert.equal(output.institutional_action_executed,false,name);
 assert.equal(output.canonical_write_performed,false,name);
 assert.equal(output.retry_authorized,false,name);
 assert.equal(output.retry_executed,false,name);
 assert.equal(output.noncanonical,true,name);
 if(code)assert.ok(output.errors.some(e=>e.code===code),name+' '+JSON.stringify(output.errors));
 count++;return output;
}
const valid=check('complete traceable context',x=>x,'HANDOFF_CONTEXT_VALIDATED');
assert.equal(valid.workflow_state,'Awaiting Response');
assert.equal(valid.institutional_state,'NOT_DETERMINED');
assert.equal(valid.action,'HOLD_FOR_RECEIVING_INSTITUTION');
for(const field of FIELDS)check('required '+field,x=>{delete x[field]},'REJECTED','MISSING_FIELD');
for(const receiver of INSTITUTIONS)check('receiver '+receiver,x=>{x.receiving_institution=receiver;x.authority_context.receiving_authority=receiver},'HANDOFF_CONTEXT_VALIDATED');
check('invalid receiver',x=>{x.receiving_institution='Navigator';x.authority_context.receiving_authority='Navigator'},'REJECTED','UNRECOGNIZED_RECEIVER');
check('mismatched authority',x=>{x.authority_context.receiving_authority='Attestor'},'REJECTED','INVALID_AUTHORITY_CONTEXT');
check('missing provenance',x=>{x.input_provenance={}},'REJECTED','EMPTY_CONTEXT');
check('reference absent provenance',x=>{delete x.input_references[0].provenance},'REJECTED','INVALID_REFERENCE');
check('reference malformed',x=>{x.input_references=[null]},'REJECTED','INVALID_REFERENCE');
check('reference wrong shape',x=>{x.input_references={}},'REJECTED','INVALID_REFERENCES');
check('trace missing correlation',x=>{delete x.traceability_context.correlation_id},'REJECTED','INVALID_TRACE');
check('trace missing step',x=>{delete x.traceability_context.originating_workflow_step},'REJECTED','INVALID_TRACE');
check('unknown promoted to success',x=>{x.unknown_state_handling.assume_success=true},'REJECTED','UNKNOWN_MUST_NOT_SUCCEED');
check('automatic retry declined',x=>{x.retry_policy.automatic_execution=true},'REJECTED','RETRY_EXECUTION_OUT_OF_SCOPE');
check('predeclared institutional outcome',x=>{x.institutional_outcome='supported'},'REJECTED','INSTITUTIONAL_DETERMINATION_FORBIDDEN');
check('predeclared canonical write',x=>{x.canonical_write_performed=true},'REJECTED','INSTITUTIONAL_DETERMINATION_FORBIDDEN');
check('bad workflow state',x=>{x.workflow_state='Published'},'REJECTED','INVALID_WORKFLOW_STATE');
check('workflow completed is not institutional completion',x=>{x.workflow_state='Completed'},'HANDOFF_CONTEXT_VALIDATED');
check('unknown workflow remains orchestration only',x=>{x.workflow_state='Partially Completed'},'HANDOFF_CONTEXT_VALIDATED');
check('timestamp malformed',x=>{x.timestamp='yesterday'},'REJECTED','INVALID_TIMESTAMP');
check('expected output lacks class',x=>{delete x.expected_output.type},'REJECTED','INVALID_OUTPUT');
check('null root',()=>null,'REJECTED','INVALID_ROOT');
check('array root',()=>[],'REJECTED','INVALID_ROOT');
const original=structuredClone(fixture);inspectHandoff(original);assert.deepEqual(original,fixture);count++;
const good=inspectHandoff(fixture);good.handoff.traceability_context.correlation_id='mutated';assert.equal(fixture.traceability_context.correlation_id,'fictional:correlation-001');count++;
assert.equal(count,47,'preflight test count must match actual execution');
console.log(`PASS ${count}/${count} synthetic IQ-008 handoff checks; no institutional operations`);
