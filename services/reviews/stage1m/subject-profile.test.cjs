'use strict';
const assert=require('node:assert/strict');
const {checkProcessRelationship}=require('./subject-profile.cjs');
const samples=require('./fictional-process-relationships.json');
const copy=x=>structuredClone(x);
let n=0;
function verify(label,change,expected,code){
 const o=checkProcessRelationship(change(copy(samples.evaluates)));
 assert.equal(o.status,expected,label);
 assert.equal(o.noncanonical,true,label);assert.equal(o.authority_granted,false,label);assert.equal(o.assertion_verified,false,label);
 if(code)assert.ok(o.errors.some(e=>e.code===code),label+' '+JSON.stringify(o.errors));
 n++;return o;
}
verify('evaluates valid',x=>x,'PROFILED_ONLY');
const rr=checkProcessRelationship(samples.results_in);assert.equal(rr.status,'PROFILED_ONLY');assert.equal(rr.profile.relationship.type,'results-in');n++;
verify('process missing',x=>{delete x.process;return x},'REJECTED','MISSING_PROCESS');
verify('relationship missing',x=>{delete x.relationship;return x},'REJECTED','MISSING_RELATIONSHIP');
verify('target missing',x=>{delete x.target;return x},'REJECTED','MISSING_TARGET');
for(const key of ['local_process_id','owning_institution','governed_context_ref','profile_version'])verify('missing '+key,x=>{delete x.process[key];return x},'REJECTED','MISSING_PROCESS_FIELD');
verify('process canonical missing',x=>{delete x.process.canonical_object;return x},'REJECTED','PROCESS_CANONICAL_FORBIDDEN');
verify('process canonical true',x=>{x.process.canonical_object=true;return x},'REJECTED','PROCESS_CANONICAL_FORBIDDEN');
verify('unknown owner',x=>{x.process.owning_institution='Other';x.relationship.asserting_institution='Other';return x},'REJECTED','INVALID_PROCESS_OWNER');
verify('predicate supports rejected',x=>{x.relationship.type='supports';return x},'REJECTED','UNSUPPORTED_PREDICATE');
verify('related-to no downgrade',x=>{x.relationship.type='related-to';return x},'REJECTED','UNSUPPORTED_PREDICATE');
verify('reverse direction rejected',x=>{x.relationship.direction='target-to-process';return x},'REJECTED','INVALID_DIRECTION');
verify('direction missing',x=>{delete x.relationship.direction;return x},'REJECTED','INVALID_DIRECTION');
verify('subject mismatch',x=>{x.relationship.subject_process_ref='OTHER';return x},'REJECTED','SUBJECT_MISMATCH');
verify('target mismatch',x=>{x.relationship.target_identifier='OTHER';return x},'REJECTED','TARGET_MISMATCH');
verify('asserting mismatch',x=>{x.relationship.asserting_institution='Certifier';return x},'REJECTED','ASSERTING_INSTITUTION_MISMATCH');
verify('provenance missing',x=>{delete x.relationship.provenance_basis;return x},'REJECTED','MISSING_PROVENANCE');
for(const key of ['identifier','object_type','owning_institution'])verify('target missing '+key,x=>{delete x.target[key];return x},'REJECTED','MISSING_TARGET_IDENTITY');
verify('unknown target owner',x=>{x.target.owning_institution='Other';return x},'REJECTED','INVALID_TARGET_OWNER');
verify('process target collision',x=>{x.target.identifier=x.process.local_process_id;x.relationship.target_identifier=x.target.identifier;return x},'REJECTED','PROCESS_TARGET_ID_COLLISION');
verify('bad canonical target flag',x=>{x.target.canonical_object='yes';return x},'REJECTED','INVALID_TARGET_CANONICAL_FLAG');
verify('unauthorized result claim',x=>{x.relationship.type='results-in';x.relationship.result_status='authorized';return x},'REJECTED','AUTHORITY_CLAIM_UNSUPPORTED');
verify('null',()=>null,'REJECTED','INVALID_INPUT');
verify('array',()=>[],'REJECTED','INVALID_INPUT');
const a=copy(samples.evaluates),frozen=copy(a);checkProcessRelationship(a);assert.deepEqual(a,frozen);n++;
const result=checkProcessRelationship(samples.evaluates);assert.equal(result.subject_kind,'governed-noncanonical-process');assert.equal(result.profile.process.canonical_object,false);n++;
assert.equal(n,31);
console.log('PASS '+n+'/'+n+' fictional IQ-005 subject-profile tests; no institutional process authenticated');
