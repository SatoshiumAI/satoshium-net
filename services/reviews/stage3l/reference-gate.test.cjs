'use strict';
const assert=require('node:assert/strict');
const {assess}=require('./reference-gate.cjs');
const fixture=require('./fictional-reference.json');
const clone=x=>structuredClone(x);
let n=0;
const check=(name,mutate,classification,reason)=>{
 const x=clone(fixture);if(mutate)mutate(x);
 const actual=assess(x);assert.equal(actual.classification,classification,name);
 assert.equal(actual.reason,reason,name);
 for(const f of ['accepted','authenticated','write_performed','production_acceptance','owner_approved'])assert.equal(actual[f],false,name+' '+f);
 assert.equal(actual.noncanonical,true,name);
 n++;
};
check('fictional candidate',null,'DOCUMENTARY_REVIEW_CANDIDATE','OWNER_CONTRACT_AND_SOURCE_AUTHORITY_NOT_VERIFIED');
check('non-object',()=>{},'DOCUMENTARY_REVIEW_CANDIDATE','OWNER_CONTRACT_AND_SOURCE_AUTHORITY_NOT_VERIFIED');
check('missing identifier',x=>delete x.source_system_identifier,'HOLD_MISSING','REQUIRED_FIELD_UNAVAILABLE');
check('missing source status',x=>delete x.source_status_claim,'HOLD_MISSING','REQUIRED_FIELD_UNAVAILABLE');
check('unknown field',x=>x.extra=true,'REJECTED','UNKNOWN_FIELD');
check('owner approval field',x=>x.owner_approved=true,'REJECTED','UNKNOWN_FIELD');
check('invalid source institution',x=>x.source_institution='Satoshium Registry','REJECTED','SOURCE_DOMAIN_MISMATCH');
check('SCRD mistaken for Package',x=>x.source_record_type='SCRD JSON','REJECTED','SOURCE_DOMAIN_MISMATCH');
check('suffix-only ID',x=>x.source_system_identifier='0000','REJECTED','INVALID_SOURCE_IDENTIFIER');
check('wrong canonical URL',x=>x.canonical_source_reference='https://example.invalid/','REJECTED','CANONICAL_SOURCE_MISMATCH');
check('wrong source version',x=>x.source_version_at_use='latest','REJECTED','INVALID_HISTORICAL_VERSION');
check('non ISO observed date',x=>x.observed_at='today','HOLD_UNKNOWN','OBSERVATION_TIME_UNVERIFIABLE');
check('missing source pin',x=>x.provenance_reference='missing','HOLD_UNKNOWN','SOURCE_PIN_MISSING');
check('write permission recipient',x=>x.recipient_context='registry-write','REJECTED','RECEIVER_PERMISSION_ESCALATION');
check('verification overclaim',x=>x.verification_state='verified','REJECTED','VERIFICATION_OVERCLAIM');
check('approval claim',x=>x.authority_claim=true,'REJECTED','AUTHORITY_ESCALATION');
check('conflicting readback',x=>x.readback_state='conflict','HOLD_CONFLICT','SOURCE_READBACK_CONFLICT');
check('failed readback',x=>x.readback_state='failed','HOLD_CONFLICT','SOURCE_READBACK_CONFLICT');
check('unknown readback',x=>x.readback_state='unknown','HOLD_UNKNOWN','SOURCE_CURRENTNESS_UNVERIFIED');
check('unavailable readback',x=>x.readback_state='unavailable','HOLD_UNKNOWN','SOURCE_CURRENTNESS_UNVERIFIED');
check('missing readback',x=>delete x.readback_state,'HOLD_UNKNOWN','SOURCE_CURRENTNESS_UNVERIFIED');
check('invented valid state',x=>x.readback_state='verified','REJECTED','UNRECOGNIZED_READBACK');
check('unknown source status',x=>x.source_status_claim='unknown','HOLD_UNKNOWN','SOURCE_STATUS_UNKNOWN');
check('unavailable source status',x=>x.source_status_claim='unavailable','HOLD_UNKNOWN','SOURCE_STATUS_UNKNOWN');
const original=clone(fixture);assess(original);assert.deepEqual(original,fixture);n++;
for(const x of [null,undefined,[],42,'test']){let z=assess(x);assert.equal(z.classification,'REJECTED');assert.equal(z.accepted,false);n++;}
assert.equal(n,30);
console.log('PASS '+n+'/'+n+' Stage 3L fictional read-only reference gate checks; no owner approval or P0 acceptance');
